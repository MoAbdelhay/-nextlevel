-- Mouj: one-time setup for a new Supabase project.
-- Paste this whole file into Supabase → SQL Editor → New query, then press Run.
-- Safe to run more than once.

create table if not exists public.listings (
  id          bigint generated by default as identity primary key,
  ref         text,
  title       text not null,
  address     text not null default '',
  city        text not null,
  price       bigint not null check (price > 0),
  type        text not null default 'house',
  beds        integer,
  baths       real,
  sqft        integer,
  description text,
  agent_name  text not null default '',
  agent_email text not null default '',
  agent_phone text,
  purpose     text not null default 'sale' check (purpose in ('sale', 'rent')),
  created_at  timestamptz not null default now()
);

-- projects set up before contact phones: add the column, email becomes optional
alter table public.listings add column if not exists agent_phone text;
alter table public.listings alter column agent_email set default '';

-- listing details (bedrooms etc. already exist): district, area, furnished, map pin
alter table public.listings add column if not exists district  text;
alter table public.listings add column if not exists area_m2   integer check (area_m2 > 0);
alter table public.listings add column if not exists furnished boolean;
alter table public.listings add column if not exists lat       double precision check (lat between -90 and 90);
alter table public.listings add column if not exists lng       double precision check (lng between -180 and 180);
alter table public.listings alter column type set default '';

create table if not exists public.photos (
  id         bigint generated by default as identity primary key,
  listing_id bigint not null references public.listings (id) on delete cascade,
  filename   text not null,
  original   text
);
create index if not exists photos_listing_id_idx on public.photos (listing_id);

-- Only the Mouj server (using the secret key) reads and writes these tables.
-- Row level security with no policies blocks the public anon/publishable key.
alter table public.listings enable row level security;
alter table public.photos   enable row level security;
grant all on public.listings, public.photos to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Public bucket for listing photos (anyone can view a photo by its link; only the server can upload).
insert into storage.buckets (id, name, public)
values ('photos', 'photos', true)
on conflict (id) do update set public = true;
